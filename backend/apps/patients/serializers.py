from rest_framework import serializers


class RegisterSerializer(serializers.Serializer):
    title = serializers.CharField(required=False, allow_blank=True)
    first_name = serializers.CharField()
    middle_name = serializers.CharField(required=False, allow_blank=True)
    last_name = serializers.CharField(required=False, allow_blank=True)
    gender = serializers.CharField()
    date_of_birth = serializers.DateField(required=False, allow_null=True)
    age_years = serializers.IntegerField(required=False, min_value=0)
    age_months = serializers.IntegerField(required=False, min_value=0)
    age_days = serializers.IntegerField(required=False, min_value=0)
    blood_group = serializers.CharField(required=False, allow_blank=True)
    mobile = serializers.CharField()
    landline = serializers.CharField(required=False, allow_blank=True)
    email = serializers.EmailField(required=False, allow_blank=True)
    marital_status = serializers.CharField(required=False, allow_blank=True)
    religion = serializers.CharField(required=False, allow_blank=True)
    address = serializers.CharField(required=False, allow_blank=True)
    country = serializers.CharField(required=False, allow_blank=True)
    state = serializers.CharField(required=False, allow_blank=True)
    city = serializers.CharField(required=False, allow_blank=True)
    area = serializers.CharField(required=False, allow_blank=True)
    zip_code = serializers.CharField(required=False, allow_blank=True)
    education = serializers.CharField(required=False, allow_blank=True)
    occupation = serializers.CharField(required=False, allow_blank=True)
    birth_mark = serializers.CharField(required=False, allow_blank=True)
    medical_history = serializers.CharField(required=False, allow_blank=True)
    comments = serializers.CharField(required=False, allow_blank=True)
    abha_id = serializers.CharField(required=False, allow_blank=True)
    id_proof_kind = serializers.CharField(required=False, allow_blank=True)
    id_proof_value = serializers.CharField(required=False, allow_blank=True)
    discount_type = serializers.CharField(required=False, allow_blank=True)
    discount_value = serializers.DecimalField(max_digits=14, decimal_places=2, required=False)
    paid_amount = serializers.DecimalField(max_digits=14, decimal_places=2, required=False)
    payment_mode = serializers.CharField(required=False, allow_blank=True)
    confirm_duplicate = serializers.BooleanField(required=False, default=False)
